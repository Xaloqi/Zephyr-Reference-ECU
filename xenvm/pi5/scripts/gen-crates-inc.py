"""Write a Yocto <recipe>-crates.inc from a Cargo.lock, in the format of
oe-core's cargo-update-recipe-crates class (crate:// SRC_URI + sha256sums).

    gen-crates-inc.py <Cargo.lock> <label> > <recipe>-crates.inc

Run it on the lockfile *after* our patch is applied (xen-vhost-frontend's
patch changes its Cargo.lock), so the crates fetched are the ones built.
Python 3.11+ (tomllib)."""
import sys
import tomllib

lock, label = sys.argv[1], sys.argv[2]
with open(lock, "rb") as f:
    pkgs = tomllib.load(f)["package"]
crates = sorted((p for p in pkgs if "crates.io" in p.get("source", "")),
                key=lambda p: (p["name"], p["version"]))
git = [p["name"] for p in pkgs if p.get("source", "").startswith("git+")]
if git:
    sys.exit("%s: git sources left in the lockfile: %s" % (lock, ", ".join(git)))
print("# Generated by xenvm/pi5/scripts/gen-crates-inc.py from %s. Do not edit." % label)
print("# %d crates from crates.io." % len(crates))
print('SRC_URI += " \\')
for p in crates:
    print("    crate://crates.io/%s/%s \\" % (p["name"], p["version"]))
print('"')
print()
for p in crates:
    print('SRC_URI[%s-%s.sha256sum] = "%s"' % (p["name"], p["version"], p["checksum"]))
